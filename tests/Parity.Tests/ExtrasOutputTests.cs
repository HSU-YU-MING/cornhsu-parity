using Parity.Cli;
using Parity.Engine;
using Parity.Engine.Model;

namespace Parity.Tests;

/// <summary>
/// 多餘元件清單(compare.extras)在 check 主控台與 Markdown 報告裡的樣子。只有「開了而且有發現」才出現一段;
/// selector 來自頁面,主控台過 ConsoleText.Safe、Markdown 表格跳脫 | 與換行、太長的截斷。
/// </summary>
[Collection(ProcessStateCollection.Name)]
public class ExtrasOutputTests
{
    private static FidelityReport Report(ExtraElements? extras, string route = "/") => new(
        route, "http://x/", "d#", [], [], new ReportSummary(1, 1, 0, 0, 0, 0, 0, 0, Severity.None), extras);

    private static readonly ExtraElement Banner = new("body > div:nth-of-type(1)", "div", new Box(0, 0, 800, 200));

    private static string Console(FidelityReport report)
    {
        var previous = System.Console.Out;
        var captured = new StringWriter();
        System.Console.SetOut(captured);
        try { CheckCommand.PrintReport(report); }
        finally { System.Console.SetOut(previous); }
        return captured.ToString();
    }

    private static string Markdown(params FidelityReport[] reports)
        => MarkdownReport.Render(reports, gateFail: false).Replace("\r\n", "\n"); // AppendLine 用平台行尾

    [Fact]
    public void Off_or_empty_prints_nothing_at_all()
    {
        foreach (var extras in new[] { null, new ExtraElements(0, []) })
        {
            Assert.DoesNotContain("extras", Console(Report(extras)));
            Assert.DoesNotContain("Extra elements", Markdown(Report(extras)));
        }
    }

    [Fact]
    public void The_console_lists_each_element_with_its_size_and_says_it_never_gates()
    {
        var output = Console(Report(new ExtraElements(1, [Banner])));

        Assert.Contains("extras: 1 element(s) on the page have no node in the design (listed only, never gated)", output);
        Assert.Contains("‹body > div:nth-of-type(1)› <div> 800×200 at (0, 0)", output);
        Assert.DoesNotContain("more", output);
    }

    [Fact]
    public void Markdown_gets_a_table_after_the_conclusion_and_says_how_many_were_left_out()
    {
        var md = Markdown(Report(new ExtraElements(5, [Banner, new("#promo", "img", new Box(16.4, -0.2, 320, 180.5))])));

        Assert.Contains("✅ PASS", md); // 結論不受影響
        Assert.Contains("### Extra elements (5) — on the page, but no node in the design (listed only, never gated)", md);
        Assert.Contains("| `body > div:nth-of-type(1)` | `div` | 800×200 at (0, 0) |", md);
        Assert.Contains("| `#promo` | `img` | 320×181 at (16, 0) |", md); // 整數 px,不印 -0
        Assert.Contains("…and 3 smaller one(s) not listed", md);
        Assert.True(md.IndexOf("### Extra elements", StringComparison.Ordinal) < md.IndexOf("Generated by Parity", StringComparison.Ordinal));
    }

    [Fact]
    public void Several_routes_get_a_route_column_and_one_combined_total()
    {
        var md = Markdown(Report(new ExtraElements(1, [Banner]), "/a"), Report(null, "/b"), Report(new ExtraElements(2, [Banner, Banner]), "/c"));

        Assert.Contains("### Extra elements (3)", md);
        Assert.Contains("| Route | Element | Tag | Size and position |", md);
        Assert.Contains("| /a | `body > div:nth-of-type(1)` |", md);
        Assert.Equal(2, md.Split("| /c | ").Length - 1);
        Assert.DoesNotContain("| /b |", md);
    }

    [Fact]
    public void A_selector_from_the_page_cannot_break_the_table_the_code_span_or_the_console()
    {
        // 頁面可以有任何 id:| 會切出新的欄、換行會結束表格、反引號會提早結束行內程式碼
        var nasty = new ExtraElement("#a|b\n::warning::x > `tick`", "div", new Box(0, 0, 100, 100));

        var md = Markdown(Report(new ExtraElements(1, [nasty])));
        var row = Assert.Single(md.Split('\n'), l => l.Contains("::warning::x"));
        Assert.Equal("| `` #a\\|b ::warning::x > `tick` `` | `div` | 100×100 at (0, 0) |", row);

        var output = Console(Report(new ExtraElements(1, [nasty])));
        Assert.Contains("#a|b\\n::warning::x", output);
        Assert.DoesNotContain(output.Replace("\r\n", "\n").Split('\n'), l => l.TrimStart().StartsWith("::", StringComparison.Ordinal));
    }

    [Fact]
    public void A_selectorselector_is_shortened_in_the_middle_for_markdown_and_kept_whole_on_the_console()
    {
        var path = "#app > " + string.Join(" > ", Enumerable.Range(1, 30).Select(i => $"div:nth-of-type({i})")) + " > section.promo";
        var element = new ExtraElement(path, "section", new Box(0, 0, 400, 300));

        var md = Markdown(Report(new ExtraElements(1, [element])));
        var cell = Assert.Single(md.Split('\n'), l => l.Contains("section.promo")).Split(" | ")[0].TrimStart('|', ' ').Trim('`');

        Assert.Equal(MarkdownReport.MaxSelectorCell, cell.Length);
        Assert.StartsWith("#app > div:nth-of-type(1)", cell); // 頭留最近的 id 錨點
        Assert.EndsWith("> section.promo", cell);              // 尾留元素本身
        Assert.Contains("…", cell);
        Assert.Contains(path, Console(Report(new ExtraElements(1, [element]))));
    }
}
